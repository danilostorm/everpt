export function normalizeLanguage(value) {
    if (typeof value !== 'string') return null;
    const code = value.trim().toLowerCase();
    if (code === 'pt' || code.startsWith('pt-')) return 'pt-BR';
    if (code === 'en' || code.startsWith('en-')) return 'en';
    return null;
}

export function browserLanguage(locales = navigator.languages?.length ? navigator.languages : [navigator.language]) {
    for (const locale of locales || []) {
        const normalized = normalizeLanguage(locale);
        if (normalized) return normalized;
    }
    return 'en';
}

function storedChoice() {
    try { return normalizeLanguage(localStorage.getItem(STORAGE_CHOICE)); }
    catch { return null; }
}

let language = storedChoice() || browserLanguage();
export function currentLanguage() { return language; }
export function isPortuguese() { return language === 'pt-BR'; }
export function t(english) { return isPortuguese() ? (translations[english] ?? english) : english; }

// Older releases saved 'en' even when users had never chosen a language.
// Migrate that implicit default to the browser locale, without discarding a
// previously saved Portuguese setting or any new explicit choice.
export function startingLanguage(previousSettings) {
    return storedChoice()
        || (normalizeLanguage(previousSettings?.language) === 'pt-BR' ? 'pt-BR' : null)
        || browserLanguage();
}

export function useLanguage(value) {
    const next = normalizeLanguage(value) || 'en';
    const changed = next !== language;
    language = next;
    document.documentElement.lang = next;
    const note = document.getElementById('note');
    if (note) note.textContent = isPortuguese()
        ? translations['Use sua conta do EverPT para jogar aqui ou no desktop, com os mesmos personagens e progresso.']
        : 'Use your EverPT account here or on desktop, with the same characters and progress.';
    if (changed) document.dispatchEvent(new CustomEvent('everpt-language-changed', { detail: { language: next } }));
    return next;
}

export function chooseLanguage(value) {
    const next = useLanguage(value);
    try { localStorage.setItem(STORAGE_CHOICE, next); }
    catch { /* Browsers with disabled storage keep the choice for this visit. */ }
    return next;
}
