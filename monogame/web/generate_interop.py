"""Generates the browser build's copy of the fork's native interop declarations (monogame/web/README.md).

Every [DllImport] of framework/MonoGame.Framework/Platform/Native/*.Interop*.cs becomes a partial method, so the compiler
reports a runtime function the web implementation lacks, or a declaration that changed. The features the browser build
has no runtime for yet (STUBBED) get an empty body instead.

Usage: python monogame/web/generate_interop.py
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SOURCE = os.path.join(HERE, '..', 'framework', 'MonoGame.Framework', 'Platform', 'Native')
OUT = os.path.join(HERE, 'Interop.g')
STUBBED = {'Media.Interop.cs', 'Storage.Interop.cs'}
EXTERN = re.compile(r'\[DllImport\([^\]]*\)\]\s*(?:\[return:[^\]]*\]\s*)?(public|private|internal) static extern ([^(]+?) (\w+)\(([^;]*?)\);', re.S)


def clean_arguments(arguments):
    return re.sub(r'\[MarshalAs\([^\]]*\)\]\s*', '', arguments)


def stub_body(result, arguments):
    lines = []
    for match in re.finditer(r'\bout\s+[\w.*]+\s+(\w+)', arguments):
        lines.append('        %s = default;' % match.group(1))
    if result.strip() != 'void':
        lines.append('        return default;')
    return '\n    {\n' + '\n'.join(lines) + ('\n' if lines else '') + '    }'


def convert(name):
    text = open(os.path.join(SOURCE, name), encoding='utf-8').read()

    def replace(match):
        access, result, method, arguments = match.groups()
        arguments = clean_arguments(arguments)
        if name in STUBBED:
            return '%s static %s %s(%s)%s' % (access, result, method, arguments, stub_body(result, arguments))
        return '%s static partial %s %s(%s);' % (access, result, method, arguments)

    return '// Generated by monogame/web/generate_interop.py from %s; do not edit.\n' % name + EXTERN.sub(replace, text)


def main():
    os.makedirs(OUT, exist_ok=True)
    for name in sorted(os.listdir(SOURCE)):
        if '.Interop' in name and name.endswith('.cs'):
            with open(os.path.join(OUT, name[:-3] + '.g.cs'), 'w', encoding='utf-8', newline='\n') as target:
                target.write(convert(name))
            print('generated', name)


if __name__ == '__main__':
    main()
